CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Existing anonymous rows remain unowned and inaccessible through the authenticated API.
-- They are retained for a deliberate administrator migration, never claimed by a new signup.
ALTER TABLE transactions ADD COLUMN user_id BIGINT REFERENCES users(id);
ALTER TABLE budgets ADD COLUMN user_id BIGINT REFERENCES users(id);
ALTER TABLE budgets DROP CONSTRAINT unique_category_month;
ALTER TABLE budgets ADD CONSTRAINT unique_user_category_month UNIQUE(user_id, category_id, budget_month);
CREATE INDEX idx_user_transaction_date ON transactions(user_id, transaction_date, id);
CREATE INDEX idx_user_category_date ON transactions(user_id, category_id, transaction_date);
