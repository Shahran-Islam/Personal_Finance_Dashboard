CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(200) NOT NULL,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    type VARCHAR(7) NOT NULL CHECK (type IN ('INCOME','EXPENSE')),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    transaction_date DATE NOT NULL
);
CREATE TABLE budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    budget_month DATE NOT NULL,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    CONSTRAINT unique_category_month UNIQUE(category_id, budget_month)
);
CREATE INDEX idx_transaction_date ON transactions(transaction_date, id);
CREATE INDEX idx_transaction_category_date ON transactions(category_id, transaction_date);
